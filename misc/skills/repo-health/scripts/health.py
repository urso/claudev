#!/usr/bin/env python3
"""Repository health metrics from git history and GitHub PRs.

Subcommands:
  collect   git history + line-age (blame at parent) -> cache
  prs       merged PRs via gh -> cache
  pending   commits without an intent label (for classification)
  metrics   compute metrics.json for a run
  dir       print the data directory

Stdlib only. Run from inside the target repository.
"""
import argparse, bisect, datetime as dt, fnmatch, json, os, re, statistics, subprocess, sys
from collections import Counter, defaultdict
from concurrent.futures import ThreadPoolExecutor

RECENT_DAYS = 21
ACTIVE_DAYS = 90
INTENTS = ['feature', 'fix', 'refactor', 'perf', 'test', 'docs', 'build', 'chore']

# Generated, vendored and lock files. Extended by .gitattributes linguist-* and
# "generated" headers at HEAD.
NOISE_GLOBS = [
    '*.lock', '*-lock.json', '*-lock.yaml', 'go.sum', '*.sum', 'pnpm-lock.yaml',
    '*.pb.go', '*_pb2.py', '*_pb2_grpc.py', '*.pb.rs', '*_grpc.pb.go', '*.pb.ts',
    '*/gen/*', 'gen/*', '*/generated/*', '*/vendor/*', 'vendor/*', '*/node_modules/*',
    '*mock*_test.go', '*/mocks/*', '*mock_*.go', '*.min.js', '*.min.css', '*.snap',
    '*/.sqlx/*', '.sqlx/*', '*.svg', '*.png', '*.jpg', '*.ico', '*.pdf',
]
GEN_HEADER = re.compile(r'Code generated .* DO NOT EDIT|@generated|auto-generated|autogenerated', re.I)


def git(*a, check=False):
    r = subprocess.run(('git',) + a, capture_output=True, text=True, errors='replace')
    if check and r.returncode:
        sys.exit(f'git {" ".join(a)}: {r.stderr.strip()}')
    return r.stdout


def data_dir():
    d = os.path.join(os.path.abspath(git('rev-parse', '--git-common-dir', check=True).strip()), 'repo-health')
    os.makedirs(d, exist_ok=True)
    return d


def read_jsonl(path):
    if not os.path.exists(path):
        return []
    with open(path) as f:
        return [json.loads(l) for l in f if l.strip()]


def append_jsonl(path, rows):
    with open(path, 'a') as f:
        for r in rows:
            f.write(json.dumps(r) + '\n')


# ---------------------------------------------------------------- collect

def rename_target(p):
    # numstat -M: "a/{old => new}/b" or "old => new"
    if ' => ' not in p:
        return p
    m = re.match(r'(.*)\{(.*) => (.*)\}(.*)', p)
    if m:
        return re.sub('//+', '/', m.group(1) + m.group(3) + m.group(4))
    return p.split(' => ')[1]


def log_commits():
    fmt = '%x1e%H%x1f%P%x1f%aN%x1f%aE%x1f%at%x1f%s%x1f%b%x1f'
    out = git('log', '--no-merges', '-M', '--numstat', f'--format={fmt}', check=True)
    for rec in out.split('\x1e')[1:]:
        f = rec.split('\x1f')
        sha, parents, name, email, ts, subj, body, rest = f[0], f[1], f[2], f[3], int(f[4]), f[5], f[6], f[7]
        files = []
        for l in rest.strip().splitlines():
            parts = l.split('\t')
            if len(parts) == 3 and parts[0] != '-':
                files.append([rename_target(parts[2]), int(parts[0]), int(parts[1])])
        m = re.search(r'This reverts commit ([0-9a-f]{7,40})', body)
        yield {'sha': sha, 'parents': parents.split(), 'author': name, 'email': email.lower(), 'ts': ts,
               'subject': subj, 'body': body.strip()[:600], 'files': files,
               'reverts': m.group(1) if m else None}


HUNK = re.compile(r'^@@ -(\d+)(?:,(\d+))? \+\d+(?:,(\d+))? @@')


AGE_VERSION = 3  # bump when line_age semantics change; invalidates the cache


def line_age(c):
    """Per file: [added, replaced-recent, replaced-legacy] using blame at parent. Blank lines are skipped."""
    if not c['parents']:
        return {}
    parent, ts = c['parents'][0], c['ts']
    res, ranges, old = {}, defaultdict(list), None
    new, header = None, False
    for l in git('diff', '-U0', '-M', '--src-prefix=a/', '--dst-prefix=b/', parent, c['sha']).splitlines():
        if l.startswith('diff --git '):
            header = True
        elif header and l.startswith('--- '):
            old = None if l == '--- /dev/null' else l[6:]
        elif header and l.startswith('+++ '):
            new = old if l == '+++ /dev/null' else l[6:]
            res.setdefault(new, [0, 0, 0])
        elif l.startswith('@@') and new:
            header = False
            m = HUNK.match(l)
            start, cnt = int(m.group(1)), 1 if m.group(2) is None else int(m.group(2))
            if cnt and old:
                ranges[(old, new)].append((start, start + cnt - 1))
        elif not header and l.startswith('+') and new and l[1:].strip():
            res[new][0] += 1
    for (o, n), rs in ranges.items():
        args = ['blame', '--porcelain', parent]
        for a, b in rs:
            args += ['-L', f'{a},{b}']
        times, sha = {}, None
        for l in git(*args, '--', o).splitlines():
            if len(l) > 41 and l[40] == ' ' and re.match(r'[0-9a-f]{40}', l):
                sha = l[:40]
            elif l.startswith('author-time '):
                times[sha] = int(l.split()[1])
            elif l.startswith('\t') and l[1:].strip():
                t = times.get(sha)
                res[n][1 if t is not None and ts - t < RECENT_DAYS * 86400 else 2] += 1
    return res


def cmd_collect(args):
    d = data_dir()
    commits = list(log_commits())
    with open(os.path.join(d, 'commits.jsonl'), 'w') as f:
        for c in commits:
            f.write(json.dumps(c) + '\n')
    age_path = os.path.join(d, 'age.jsonl')
    cached = [r for r in read_jsonl(age_path) if r.get('v') == AGE_VERSION]
    done = {r['sha'] for r in cached}
    todo = [c for c in commits if c['sha'] not in done]
    print(f'{len(commits)} commits, computing line age for {len(todo)}', file=sys.stderr)
    with ThreadPoolExecutor(os.cpu_count() or 4) as ex:
        rows = [{'sha': c['sha'], 'v': AGE_VERSION, 'files': r} for c, r in zip(todo, ex.map(line_age, todo))]
    with open(age_path, 'w') as f:
        for r in cached + rows:
            f.write(json.dumps(r) + '\n')
    print(d)


# ---------------------------------------------------------------- prs

PR_QUERY = '''query($o:String!,$n:String!,$endCursor:String){repository(owner:$o,name:$n){
pullRequests(first:100,after:$endCursor,states:MERGED,orderBy:{field:CREATED_AT,direction:DESC}){
pageInfo{hasNextPage endCursor}
nodes{number title createdAt mergedAt additions deletions changedFiles isDraft author{login}
commits{totalCount}
reviews(first:100){nodes{submittedAt state author{login}}}}}}}'''


def cmd_prs(args):
    r = subprocess.run(['gh', 'repo', 'view', '--json', 'owner,name'], capture_output=True, text=True)
    if r.returncode:
        sys.exit(f'gh repo view failed: {r.stderr.strip()}')
    repo = json.loads(r.stdout)
    r = subprocess.run(['gh', 'api', 'graphql', '--paginate', '-F', f'o={repo["owner"]["login"]}',
                        '-F', f'n={repo["name"]}', '-f', f'query={PR_QUERY}'], capture_output=True, text=True)
    if r.returncode:
        sys.exit(f'gh api failed: {r.stderr.strip()}')
    dec, pos, prs = json.JSONDecoder(), 0, []
    out = r.stdout
    while pos < len(out):
        while pos < len(out) and out[pos].isspace():
            pos += 1
        if pos >= len(out):
            break
        page, pos = dec.raw_decode(out, pos)
        for n in page['data']['repository']['pullRequests']['nodes']:
            author = (n['author'] or {}).get('login', 'ghost')
            reviews = [{'at': v['submittedAt'], 'state': v['state'], 'by': (v['author'] or {}).get('login')}
                       for v in n['reviews']['nodes'] if v['submittedAt']]
            prs.append({'number': n['number'], 'title': n['title'], 'author': author,
                        'created': n['createdAt'], 'merged': n['mergedAt'],
                        'size': n['additions'] + n['deletions'], 'files': n['changedFiles'],
                        'commits': n['commits']['totalCount'],
                        'reviews': [v for v in reviews if v['by'] != author]})
    with open(os.path.join(data_dir(), 'prs.jsonl'), 'w') as f:
        for p in prs:
            f.write(json.dumps(p) + '\n')
    print(f'{len(prs)} merged PRs', file=sys.stderr)


# ---------------------------------------------------------------- intent

KEYWORDS = [
    ('fix', r'\bfix|flaky|deadlock|\bbug|crash|race\b|regression|hotfix'),
    ('perf', r'\bperf|optimi[sz]|faster|speed ?up|latency'),
    ('docs', r'^docs?\b|readme|\bdocument|specification'),
    ('test', r'^tests?\b|\btests?:|e2e|integration test|unit test'),
    ('build', r'^(ci|build)\b|\bci\b|helm|chart|docker|nix|deps|dependenc|bump|workflow'),
    ('chore', r'^chore|clippy|lint|fmt|format|edition|rename|typo|cleanup'),
    ('refactor', r'refactor|extract|split|restructure|simplif|migrate|consolidate|decouple|reorgani'),
]


def keyword_intent(c):
    s = c['subject'].lower()
    m = re.match(r'^(\w+)(\(.+?\))?!?:', s)  # conventional commit prefix
    if m:
        p = m.group(1)
        p = {'feat': 'feature', 'ci': 'build', 'style': 'chore', 'doc': 'docs', 'tests': 'test'}.get(p, p)
        if p in INTENTS:
            return p
    for k, rx in KEYWORDS:
        if re.search(rx, s):
            return k
    return 'feature'


def load_intents(d):
    res = {}
    p = os.path.join(d, 'intent.tsv')
    if os.path.exists(p):
        for l in open(p):
            parts = l.split()
            if len(parts) >= 2 and parts[1] in INTENTS:
                res[parts[0]] = parts[1]
    return res, sorted({len(k) for k in res}, reverse=True)


def lookup(intents, sha):
    """Label whose key is a prefix of sha. Checks each distinct key length once."""
    m, lens = intents
    return next((m[sha[:n]] for n in lens if sha[:n] in m), None)


def expand(shas, prefix):
    """Full sha in sorted list shas starting with prefix, or None."""
    i = bisect.bisect_left(shas, prefix)
    return shas[i] if prefix and i < len(shas) and shas[i].startswith(prefix) else None


def revert_chain(commits):
    """Revert commits and everything they (transitively) revert."""
    shas = sorted(c['sha'] for c in commits)
    drop = set()
    for c in commits:
        if c['reverts'] or re.match(r'(?i)^revert\b', c['subject']):
            drop.add(c['sha'])
            if c['reverts']:
                t = expand(shas, c['reverts'])
                if t:
                    drop.add(t)
    return drop


def cmd_pending(args):
    d = data_dir()
    commits = read_jsonl(os.path.join(d, 'commits.jsonl'))
    intents, drop = load_intents(d), revert_chain(commits)
    n = 0
    for c in commits:
        if c['sha'] in drop or lookup(intents, c['sha']):
            continue
        add = sum(f[1] for f in c['files'])
        dele = sum(f[2] for f in c['files'])
        dirs = Counter('/'.join(f[0].split('/')[:2]) for f in c['files']).most_common(3)
        body = ' '.join(c['body'].split())[:160]
        print(f"{c['sha'][:10]}\t+{add}/-{dele}\t{','.join(x for x, _ in dirs)}\t{c['subject']}" +
              (f' || {body}' if body else ''))
        n += 1
        if args.limit and n >= args.limit:
            break
    print(f'{n} pending', file=sys.stderr)


# ---------------------------------------------------------------- metrics

def noise_set(paths):
    noise = {p for p in paths if any(fnmatch.fnmatch(p, g) or fnmatch.fnmatch('/' + p, '*/' + g) for g in NOISE_GLOBS)}
    head = set(git('ls-files').splitlines())
    r = subprocess.run(['git', 'check-attr', '--stdin', 'linguist-generated', 'linguist-vendored'],
                       input='\n'.join(p for p in paths if p in head), capture_output=True, text=True)
    for l in r.stdout.splitlines():
        p, _, v = l.rsplit(': ', 2)
        if v == 'set' or v == 'true':
            noise.add(p)
    for p in head - noise:
        try:
            with open(p, 'rb') as f:
                chunk = f.read(2048)
        except OSError:
            continue
        if b'\0' in chunk or GEN_HEADER.search(chunk.decode('utf-8', 'replace')):
            noise.add(p)
    return noise


def file_stats(path):
    """Lines and whitespace complexity (sum of indentation levels)."""
    try:
        with open(path, errors='replace') as f:
            lines = f.read().splitlines()
    except OSError:
        return 0, 0
    loc = cx = 0
    for l in lines:
        s = l.lstrip()
        if not s:
            continue
        loc += 1
        ind = l[:len(l) - len(s)]
        cx += ind.count('\t') + ind.count(' ') // 4
    return loc, cx


def build_areas(loc_by_file, split_frac=0.15):
    total = sum(loc_by_file.values()) or 1
    tree = defaultdict(int)
    for p, n in loc_by_file.items():
        parts = p.split('/')
        for i in range(1, len(parts)):
            tree['/'.join(parts[:i])] += n
    children = defaultdict(set)
    for k in tree:
        parent = k.rsplit('/', 1)[0] if '/' in k else ''
        children[parent].add(k)
    areas = []

    def walk(d):
        kids = children.get(d, set())
        big = d == '' or tree[d] > split_frac * total
        # descend through single-child chains (e.g. services/x -> services/x/src)
        if d and kids and max(tree[k] for k in kids) > 0.9 * tree[d]:
            big = True
        if big and kids:
            for k in kids:
                walk(k)
            if d:
                areas.append(d)  # files directly in d
        elif d:
            areas.append(d)
    walk('')
    return sorted(areas, key=len, reverse=True)


def area_of(path, areas):
    for a in areas:
        if path.startswith(a + '/'):
            return a
    parts = path.split('/')
    return '/'.join(parts[:2]) if len(parts) > 2 else (parts[0] if len(parts) > 1 else '(root)')


class Identities:
    """Merge author identities sharing a name or email, plus explicit aliases."""

    def __init__(self, commits, aliases):
        self.parent = {}
        for c in commits:
            self.union('n:' + c['author'].lower(), 'e:' + c['email'])
        for a in aliases:
            x, y = a.split('=', 1)
            self.union('n:' + x.strip().lower(), 'n:' + y.strip().lower())
        count = defaultdict(Counter)
        for c in commits:
            count[self.find('n:' + c['author'].lower())][c['author']] += 1
        self.name = {k: v.most_common(1)[0][0] for k, v in count.items()}
        # longest display name wins ties toward full names over handles
        for k, v in count.items():
            self.name[k] = max(v, key=lambda n: (len(n.split()), v[n]))
        self.by_email = {}
        for c in commits:
            self.by_email[c['email']] = self.of(c['author'])

    def find(self, x):
        self.parent.setdefault(x, x)
        while self.parent[x] != x:
            self.parent[x] = self.parent[self.parent[x]]
            x = self.parent[x]
        return x

    def union(self, a, b):
        self.parent[self.find(a)] = self.find(b)

    def of(self, name):
        return self.name[self.find('n:' + name.lower())]


def month(ts):
    return dt.datetime.fromtimestamp(ts, dt.timezone.utc).strftime('%Y-%m')


def pct(a, b):
    return round(100 * a / b, 1) if b else 0.0


def blame_head(path, ignore_file):
    out = git('blame', '--porcelain', '-w', '--ignore-revs-file', ignore_file, 'HEAD', '--', path)
    res, sha = Counter(), None
    for l in out.splitlines():
        if len(l) > 41 and l[40] == ' ' and re.match(r'[0-9a-f]{40}', l):
            sha = l[:40]
        elif l.startswith('\t') and l[1:].strip():
            res[sha] += 1
    return path, res


def quantile(xs, q):
    if not xs:
        return None
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(q * (len(xs) - 1) + 0.5))]


def parse_ts(s):
    return dt.datetime.fromisoformat(s.replace('Z', '+00:00')).timestamp()


def cmd_metrics(args):
    d = data_dir()
    commits = read_jsonl(os.path.join(d, 'commits.jsonl'))
    if not commits:
        sys.exit('no data, run collect first')
    age = {r['sha']: r['files'] for r in read_jsonl(os.path.join(d, 'age.jsonl')) if r.get('v') == AGE_VERSION}
    if not age:
        sys.exit('line-age cache is outdated, run collect')
    intents = load_intents(d)
    ids = Identities(commits, args.alias or [])
    drop = revert_chain(commits)
    now = max(c['ts'] for c in commits)
    all_paths = {f[0] for c in commits for f in c['files']}
    noise = noise_set(all_paths)

    head_files = [p for p in git('ls-files').splitlines() if p not in noise and os.path.isfile(p)]
    stats = {p: file_stats(p) for p in head_files}
    stats = {p: s for p, s in stats.items() if s[0]}
    loc = {p: s[0] for p, s in stats.items()}
    areas = build_areas(loc)

    live = [c for c in commits if c['sha'] not in drop]
    labelled = 0
    for c in live:
        i = lookup(intents, c['sha'])
        labelled += i is not None
        c['intent'] = i or keyword_intent(c)
        c['who'] = ids.of(c['author'])
        c['month'] = month(c['ts'])
        c['files'] = [f for f in c['files'] if f[0] not in noise]

    months = sorted({c['month'] for c in live})
    churn = defaultdict(lambda: defaultdict(int))           # month -> intent -> lines
    rework_m = defaultdict(lambda: [0, 0, 0])               # month -> new, recent, legacy
    rework_a = defaultdict(lambda: [0, 0, 0])
    rework_i = defaultdict(lambda: [0, 0, 0])
    area_intent = defaultdict(lambda: defaultdict(int))     # area -> intent -> lines
    area_fix_commits = defaultdict(set)
    area_commits = defaultdict(set)
    revs = Counter()
    revs_recent = Counter()
    file_authors = defaultdict(Counter)
    for c in live:
        ages = age.get(c['sha'], {})
        for f in c['files']:
            p = f[0]
            # non-blank line counts from line age; numstat only as fallback
            n, rec, leg = ages.get(p, [f[1], 0, f[2]])
            f[1], f[2] = n, rec + leg
            ar = area_of(p, areas)
            churn[c['month']][c['intent']] += n + rec + leg
            area_intent[ar][c['intent']] += n + rec + leg
            area_commits[ar].add(c['sha'])
            if c['intent'] == 'fix':
                area_fix_commits[ar].add(c['sha'])
            for bucket in (rework_m[c['month']], rework_a[ar], rework_i[c['intent']]):
                bucket[0] += n
                bucket[1] += rec
                bucket[2] += leg
            if c['intent'] not in ('chore',):
                revs[p] += 1
                if now - c['ts'] < ACTIVE_DAYS * 86400:
                    revs_recent[p] += 1
                file_authors[p][c['who']] += 1

    def rework_rows(m, keys):
        return [{'key': k, 'new': m[k][0], 'recent': m[k][1], 'legacy': m[k][2],
                 'rework_pct': pct(m[k][1], sum(m[k]))} for k in keys]

    area_loc = Counter()
    for p, n in loc.items():
        area_loc[area_of(p, areas)] += n
    top_areas = [a for a, _ in area_loc.most_common() if area_loc[a] >= 0.01 * sum(loc.values())]

    # hotspots
    max_rev = max((revs[p] for p in stats), default=1) or 1
    max_cx = max((s[1] for s in stats.values()), default=1) or 1
    hot = []
    for p, (n, cx) in stats.items():
        if revs[p] == 0:
            continue
        hot.append({'path': p, 'area': area_of(p, areas), 'revisions': revs[p], 'recent_revisions': revs_recent[p],
                    'loc': n, 'complexity': cx, 'authors': len(file_authors[p]),
                    'score': round((revs[p] / max_rev) * (cx / max_cx), 4)})
    hot.sort(key=lambda h: -h['score'])

    # change coupling
    pair = Counter()
    for c in live:
        if c['intent'] in ('chore', 'build'):
            continue
        fs = sorted({f[0] for f in c['files']})
        if 2 <= len(fs) <= 30:
            for i in range(len(fs)):
                for j in range(i + 1, len(fs)):
                    pair[(fs[i], fs[j])] += 1
    coupling = []
    for (a, b), n in pair.items():
        if n < args.min_shared or revs[a] < args.min_shared or revs[b] < args.min_shared:
            continue
        degree = n / ((revs[a] + revs[b]) / 2)
        if degree < 0.3:
            continue
        aa, ab = area_of(a, areas), area_of(b, areas)
        nested = aa == ab or aa.startswith(ab + '/') or ab.startswith(aa + '/')
        coupling.append({'a': a, 'b': b, 'shared': n, 'degree': round(degree, 2), 'cross_area': not nested,
                         'test_pair': bool(re.search(r'test', a + b, re.I))})
    coupling.sort(key=lambda x: (-x['cross_area'], -x['shared'], -x['degree']))

    # ownership + survival from blame at HEAD
    # Blame passes through revert chains, chores and the repo's own ignore list.
    sha_info = {c['sha']: c for c in commits}
    ignore = set(drop) | {c['sha'] for c in live if c['intent'] == 'chore'}
    repo_ignore = os.path.join(git('rev-parse', '--show-toplevel').strip(), '.git-blame-ignore-revs')
    if os.path.exists(repo_ignore):
        shas = sorted(sha_info)
        for l in open(repo_ignore):
            full = expand(shas, l.split('#')[0].strip())
            if full:
                ignore.add(full)
    ignore_file = os.path.join(d, 'blame-ignore-revs')
    with open(ignore_file, 'w') as f:
        f.write('\n'.join(sorted(ignore)) + '\n')
    own = defaultdict(Counter)
    own_sha = defaultdict(Counter)
    cohort_alive = Counter()
    with ThreadPoolExecutor(os.cpu_count() or 4) as ex:
        for p, res in ex.map(lambda p: blame_head(p, ignore_file), list(stats)):
            ar = area_of(p, areas)
            for sha, n in res.items():
                c = sha_info.get(sha)
                who = ids.of(c['author']) if c else 'unknown'
                own[ar][who] += n
                own['(all)'][who] += n
                own_sha[ar][sha] += n
                cohort_alive[month(c['ts']) if c else 'unknown'] += n
    # History-based knowledge: lines added per author, halving every 180 days.
    # Reviewers get the PR's changed lines per area, same decay. Commits map to
    # PRs via the "(#123)" suffix of squash merges.
    prs = read_jsonl(os.path.join(d, 'prs.jsonl'))
    pr_by_num = {p['number']: p for p in prs}
    login_name = Counter()
    pr_of = {}
    for c in live:
        m = re.search(r'\(#(\d+)\)\s*$', c['subject'])
        p = pr_by_num.get(int(m.group(1))) if m else None
        if p:
            pr_of[c['sha']] = p
            login_name[(p['author'], c['who'])] += 1
    names = {}
    for (login, who), _ in login_name.most_common():
        names.setdefault(login, who)

    def reviewer(login):
        return names.get(login, login)
    is_bot = re.compile(r'\[bot\]$|^copilot|-bot$|^github-actions', re.I)
    know = defaultdict(Counter)
    review = defaultdict(Counter)
    reviewed_lines = Counter()
    pr_lines = Counter()
    for c in live:
        if c['intent'] == 'chore':
            continue
        w = 0.5 ** ((now - c['ts']) / (180 * 86400))
        p = pr_of.get(c['sha'])
        revs_ = {reviewer(r['by']) for r in (p['reviews'] if p else []) if r['by'] and not is_bot.search(r['by'])}
        revs_.discard(c['who'])
        for path, a, r in c['files']:
            ar = area_of(path, areas)
            for key in (ar, '(all)'):
                know[key][c['who']] += a * w
                if p:
                    pr_lines[key] += a + r
                    if revs_:
                        reviewed_lines[key] += a + r
                for who in revs_:
                    review[key][who] += (a + r) * w
    last_commit = {}
    for c in live:
        last_commit[c['who']] = max(last_commit.get(c['who'], 0), c['ts'])
    active = {w for w, t in last_commit.items() if now - t < ACTIVE_DAYS * 86400}
    ownership = []
    for ar in ['(all)'] + top_areas:
        cnt = own.get(ar)
        if not cnt:
            continue
        total = sum(cnt.values())
        ranked = cnt.most_common()
        acc = k = 0
        while acc <= total / 2:
            acc += ranked[k][1]
            k += 1
        kn = know.get(ar, Counter())
        ktotal = sum(kn.values())
        dom = None
        if ar != '(all)' and own_sha[ar]:
            sha, n = own_sha[ar].most_common(1)[0]
            c = sha_info.get(sha, {})
            dom = {'sha': sha[:10], 'subject': c.get('subject', ''), 'author': ids.of(c['author']) if c else 'unknown',
                   'intent': lookup(intents, sha) or (keyword_intent(c) if c else None), 'pct': pct(n, total)}
        ownership.append({'area': ar, 'lines': total, 'truck_factor': k,
                          'top': [{'author': a, 'lines': n, 'pct': pct(n, total)} for a, n in ranked[:5]],
                          'knowledge': [{'author': a, 'pct': pct(n, ktotal)} for a, n in kn.most_common(3)],
                          'reviewers': [{'author': a, 'pct': pct(n, sum(review[ar].values()))}
                                        for a, n in review[ar].most_common(3)],
                          'reviewed_pct': pct(reviewed_lines[ar], pr_lines[ar]),
                          'dominant_commit': dom,
                          'inactive_pct': pct(sum(n for a, n in ranked if a not in active), total)})
    added_by_month = Counter()
    for c in live:
        added_by_month[c['month']] += sum(f[1] for f in c['files'])
    survival = [{'month': m, 'added': added_by_month[m], 'alive': cohort_alive[m],
                 'survival_pct': pct(cohort_alive[m], added_by_month[m])} for m in months]

    # PR flow
    pr_months = defaultdict(list)
    for p in prs:
        created, merged = parse_ts(p['created']), parse_ts(p['merged'])
        first = min((parse_ts(r['at']) for r in p['reviews']), default=None)
        p['cycle_h'] = (merged - created) / 3600
        p['first_review_h'] = (first - created) / 3600 if first else None
        p['rounds'] = len(p['reviews'])
        pr_months[month(merged)].append(p)
    pr_rows = []
    for m in sorted(pr_months):
        ps = pr_months[m]
        fr = [p['first_review_h'] for p in ps if p['first_review_h'] is not None]
        pr_rows.append({'month': m, 'merged': len(ps),
                        'cycle_p50_h': round(quantile([p['cycle_h'] for p in ps], .5), 1),
                        'cycle_p90_h': round(quantile([p['cycle_h'] for p in ps], .9), 1),
                        'first_review_p50_h': round(quantile(fr, .5), 1) if fr else None,
                        'size_p50': quantile([p['size'] for p in ps], .5),
                        'size_p90': quantile([p['size'] for p in ps], .9),
                        'rounds_p50': quantile([p['rounds'] for p in ps], .5),
                        'unreviewed_pct': pct(sum(1 for p in ps if not p['reviews']), len(ps))})
    slow = sorted(prs, key=lambda p: -p['cycle_h'])[:10]

    total_rw = [sum(v[i] for v in rework_m.values()) for i in range(3)]
    out = {
        'generated': dt.datetime.now(dt.timezone.utc).isoformat(timespec='seconds'),
        'repo': os.path.basename(git('rev-parse', '--show-toplevel').strip()),
        'head': git('rev-parse', '--short', 'HEAD').strip(),
        'params': {'recent_days': RECENT_DAYS, 'active_days': ACTIVE_DAYS},
        'summary': {
            'commits': len(commits), 'analyzed_commits': len(live), 'revert_chain_commits': len(drop),
            'intent_labelled': labelled, 'authors': len({c['who'] for c in live}), 'active_authors': len(active),
            'first': month(min(c['ts'] for c in commits)), 'last': month(now),
            'loc': sum(loc.values()), 'files': len(loc),
            'churn': sum(sum(v.values()) for v in churn.values()),
            'rework_pct': pct(total_rw[1], sum(total_rw)),
            'merged_prs': len(prs),
        },
        'areas': [{'area': a, 'loc': area_loc[a]} for a in top_areas],
        'churn_by_month': [{'month': m, **{i: churn[m][i] for i in INTENTS}} for m in months],
        'rework_by_month': rework_rows(rework_m, months),
        'rework_by_area': sorted(rework_rows(rework_a, [a for a in top_areas if a in rework_a]),
                                 key=lambda r: -r['rework_pct']),
        'rework_by_intent': rework_rows(rework_i, [i for i in INTENTS if i in rework_i]),
        'fix_by_area': sorted([{'area': a, 'lines': sum(area_intent[a].values()),
                                'fix_lines': area_intent[a]['fix'],
                                'fix_pct': pct(area_intent[a]['fix'], sum(area_intent[a].values())),
                                'commits': len(area_commits[a]), 'fix_commits': len(area_fix_commits[a])}
                               for a in top_areas if area_commits[a]], key=lambda r: -r['fix_pct']),
        'intent_by_area': {a: dict(area_intent[a]) for a in top_areas},
        'hotspots': hot[:25],
        'coupling': coupling[:30],
        'ownership': ownership,
        'survival': survival,
        'pr_by_month': pr_rows,
        'pr_slowest': [{'number': p['number'], 'title': p['title'], 'author': p['author'],
                        'cycle_h': round(p['cycle_h'], 1), 'size': p['size'], 'rounds': p['rounds']} for p in slow],
    }
    run = os.path.join(d, 'runs', dt.date.today().isoformat())
    os.makedirs(run, exist_ok=True)
    with open(os.path.join(run, 'metrics.json'), 'w') as f:
        json.dump(out, f, indent=1)
    print(run)


